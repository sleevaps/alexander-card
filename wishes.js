const opening = [
  'Удачи', 'Сил', 'Своих рядом', 'Свободы',
  'Смелых планов', 'Пустых понедельников', 'Длинных выходных',
  'Своего места', 'Крепкого сна', 'Тёплых встреч',
  'Кофе по утрам', 'Поездок к морю', 'Смешных историй',
  'Денег на мечты', 'Спокойствия', 'Дела по душе',
  'Дороги домой', 'Горящих глаз', 'Света в окнах', 'Свежих идей',
  'Музыки погромче', 'Весёлой суеты', 'Терпения', 'Поводов собой гордиться'
];

const descriptions = ['ярких', 'редких', 'крутых', 'тёплых', 'неожиданных', 'долгожданных', 'сюрреальных', 'особенных', 'прекрасных', 'запоминающихся', 'душевных'];
const endings = ['встреч', 'открытий', 'сюрпризов', 'вечеров', 'приключений', 'поездок', 'разговоров', 'моментов', 'совпадений', 'историй', 'дней'];

export function wishAt(index) {
  if (index < opening.length) return opening[index];
  const cycle = index - opening.length;
  const adjective = descriptions[(cycle * 7 + Math.floor(cycle / endings.length) * 3) % descriptions.length];
  const noun = endings[(cycle * 3 + 4) % endings.length];
  return adjective + ' ' + noun;
}
